/**
 * The data every part of the build shares: the nav tree, site metadata and
 * what scripts/build_docs_data.py read from sot. Read fresh on each call so
 * `eleventy --serve` picks up changes.
 */
import { existsSync, readFileSync } from "node:fs";
import path from "node:path";

export const DOCS_ROOT = path.resolve(import.meta.dirname, "..");
export const REPO_ROOT = path.resolve(DOCS_ROOT, "..");
const DATA = path.join(DOCS_ROOT, "src/_data");

export interface NavItem {
  title: string;
  url: string;
  command?: string;
  optional?: boolean;
}

export interface NavDir {
  dir: string;
  children: NavItem[];
}

export type NavEntry = NavItem | NavDir;

export interface Nav {
  windows: { name: string; url: string }[];
  tree: NavEntry[];
}

export interface Site {
  title: string;
  tagline: string;
  description: string;
  repo: string;
}

export interface Binding {
  id: string;
  key: string;
  description: string;
}

export interface SotData {
  version: string;
  commands: Record<string, { usage: string; help: string; summary?: string }>;
  keys: Binding[];
  config_example: string;
  themes: string[];
  logos: Record<string, string[]>;
}

export interface Overview {
  intro: string[];
  views: { key: string; name: string; shows: string }[];
  commands: { command: string; url: string; does: string }[];
}

const readJson = <T>(file: string): T => JSON.parse(readFileSync(path.join(DATA, file), "utf8")) as T;

export const navData = (): Nav => readJson<Nav>("nav.json");
export const siteData = (): Site => readJson<Site>("site.json");
export const overviewData = (): Overview => readJson<Overview>("overview.json");

/** Generated by scripts/build_docs_data.py; missing until that has run. */
export function sotData(): SotData | undefined {
  return existsSync(path.join(DATA, "sot.json")) ? readJson<SotData>("sot.json") : undefined;
}

/** Every page in tree order. */
export function flatten(tree: NavEntry[]): NavItem[] {
  return tree.flatMap((entry) => ("dir" in entry ? entry.children : [entry]));
}

/** What `sot --config-path` prints before the config file exists. */
export function configPathOutput(): string | undefined {
  const example = sotData()?.config_example;
  return example && `~/.config/sot/config.toml (not created yet)\n\n${example}`;
}

/** A Markdown file from the repository root, without its `# Title`. */
export function repoMarkdownSource(file: string): string {
  return readFileSync(path.join(REPO_ROOT, file), "utf8").replace(/^# .*\n/, "");
}

/** The install commands, shared by the home page and its Markdown copy. */
export function installSnippet(): string {
  return readFileSync(path.join(DOCS_ROOT, "src/_includes/snippets/install.md"), "utf8").trim();
}
